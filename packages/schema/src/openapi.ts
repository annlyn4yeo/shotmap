/**
 * docs/openapi.json and docs/API.md, both generated from the route table in api.ts, so
 * the schemas, the OpenAPI document and the prose cannot drift. A test fails when the
 * committed docs/openapi.json is not what this produces.
 */
import { z } from 'zod';
import { ErrorSchema, ROUTES, type Route } from './api';
import { API_VERSION, ATTRIBUTION, CACHE_CONTROL, HEADERS, LIMITS } from './contract';
import { OUTCOMES } from './constants';

type Json = Record<string, unknown>;

function schemaOf(schema: z.ZodType, io: 'input' | 'output' = 'output'): Json {
  const json = z.toJSONSchema(schema, {
    target: 'draft-2020-12',
    io,
    unrepresentable: 'any',
  }) as Json;
  delete json.$schema;
  return json;
}

const pascal = (id: string) => id.charAt(0).toUpperCase() + id.slice(1);

function parameters(route: Route): Json[] {
  const out: Json[] = [];
  for (const [where, object] of [
    ['path', route.params],
    ['query', route.query],
  ] as const) {
    if (!object) continue;
    for (const [name, field] of Object.entries(object.shape)) {
      const f = field as z.ZodType;
      out.push({
        name,
        in: where,
        required: where === 'path' || !f.safeParse(undefined).success,
        ...(f.description ? { description: f.description } : {}),
        schema: schemaOf(f, 'input'),
      });
    }
  }
  return out;
}

const responseHeaders = {
  [HEADERS.etag]: {
    description:
      'A strong validator: the release plus a hash of the path and query. Send it back as If-None-Match to get a 304.',
    schema: { type: 'string' },
  },
  [HEADERS.cacheControl]: {
    description: `${CACHE_CONTROL.pinned} when the request names the current release with ?v=<release>; otherwise ${CACHE_CONTROL.floating}.`,
    schema: { type: 'string' },
  },
  [HEADERS.release]: {
    description: 'The data release, the same value as `release` in the body.',
    schema: { type: 'string', pattern: '^r[0-9a-f]{12}$' },
  },
};

export function buildOpenApi(): Json {
  const schemas: Record<string, Json> = { Error: schemaOf(ErrorSchema) };
  const paths: Record<string, Json> = {};
  const error = (description: string) => ({
    description,
    content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } },
  });
  for (const route of ROUTES) {
    const name = `${pascal(route.id)}Response`;
    schemas[name] = schemaOf(route.response);
    paths[route.path] = {
      get: {
        operationId: route.id,
        summary: route.summary,
        ...(route.notes ? { description: route.notes } : {}),
        parameters: parameters(route),
        responses: {
          '200': {
            description: 'The data, wrapped with the release and the attribution.',
            headers: responseHeaders,
            content: {
              'application/json': { schema: { $ref: `#/components/schemas/${name}` } },
            },
          },
          '304': {
            description: 'Not modified: the If-None-Match ETag is still current.',
          },
          '400': error('The request is malformed, or asks for too many rows.'),
          '404': error('No such match or player.'),
        },
      },
    };
  }
  return {
    openapi: '3.1.0',
    info: {
      title: 'Shotmap API',
      version: API_VERSION,
      description: `Read-only football shot data. ${ATTRIBUTION.text}. Every response carries the data release it comes from and the attribution to show.`,
      'x-attribution': ATTRIBUTION,
    },
    servers: [{ url: '/' }],
    paths,
    components: { schemas },
  };
}

