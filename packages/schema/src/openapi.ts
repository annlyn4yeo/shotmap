export function buildApiMarkdown(): string {
  const lines: string[] = [];
  const out = (...l: string[]) => lines.push(...l);
  out(
    '# Shotmap API v1',
    '',
    'Generated by `pnpm --filter @shotmap/schema generate` from the route table in `packages/schema/src/api.ts`. Do not edit by hand. The machine-readable form is `docs/openapi.json`. Read-only, `GET` only, JSON.',
    '',
    '## Every response',
    '',
    '```json',
    '{ "release": "r9733bd358bf4", "attribution": { "source": "StatsBomb", "text": "Data by StatsBomb", "url": "https://statsbomb.com", "terms": "https://github.com/statsbomb/open-data" }, "data": { } }',
    '```',
    '',
    '- `release` is the data release: `r` and 12 hex digits, a hash of everything ingest wrote. It changes exactly when the data does.',
    `- \`attribution\` must be shown wherever the data is. The wording is a placeholder until StatsBomb has been asked (docs/LICENCE-NOTES.md).`,
    '',
    '| Header | Value |',
    '| --- | --- |',
    `| \`${HEADERS.etag}\` | A strong validator: the release plus a hash of the path and query. \`If-None-Match\` gets a 304. |`,
    `| \`${HEADERS.cacheControl}\` | \`${CACHE_CONTROL.pinned}\` when the request names the current release with \`?v=<release>\`; otherwise \`${CACHE_CONTROL.floating}\`. |`,
    `| \`${HEADERS.release}\` | The release again, so a cache can key on it without parsing the body. |`,
    '',
    'Errors are `{ "error": { "code", "message" } }` with `bad_request` (400), `not_found` (404), `too_many_rows` (400) or `internal` (500).',
    '',
    '## Identity',
    '',
    '- A shot has a global id (`shot`) and a position in its match (`seq`). `#shot=12` links in the app mean `seq`.',
    '- A player is a StatsBomb `player` id, never a name. A player has no team: `/v1/players/{id}` lists every team they shot for.',
    '- A team is a StatsBomb `team` id, and a shot also has a `side` (0 home, 1 away).',
    '',
    '## Shot columns',
    '',
    'Shots travel as columns: `{ "n": 28, "cols": { "shot": [...], "seq": [...], ... } }`, every column `n` long.',
    '',
    '| Column | Meaning |',
    '| --- | --- |',
    ...columns.map(([name, text]) => `| \`${name}\` | ${text} |`),
    '',
    'Shootout kicks are rows with `period` 5, always after open play within a match, so `seq` is stable. Outcomes group into five marks: ' +
      OUTCOMES.join(', ') +
      '.',
    '',
    '## Endpoints',
    '',
  );
  for (const route of ROUTES) {
    out(`### \`GET ${route.path}\``, '', route.summary + '.', '');
    if (route.notes) out(route.notes, '');
    const params = parameters(route);
    if (params.length) {
      out('| Parameter | In | Required | Meaning |', '| --- | --- | --- | --- |');
      for (const p of params)
        out(
          `| \`${String(p.name)}\` | ${String(p.in)} | ${p.required ? 'yes' : 'no'} | ${typeof p.description === 'string' ? p.description : ''} |`,
        );
      out('');
    }
  }
  out(
    '## Limits',
    '',
    'Sized for the design ceiling of about 10,000 matches and 500,000 shots.',
    '',
    `- Match pages: ${LIMITS.matchesPageDefault} by default, ${LIMITS.matchesPageMax} at most; \`next\` is an opaque cursor.`,
    `- Search: ${LIMITS.searchPerKind} results per kind. Every word typed must be the start of a word.`,
    `- A player's shots: ${LIMITS.playerShotsDefault} rows unless \`limit\` asks for more, ${LIMITS.playerShotsMax} at most, with \`truncated\` saying whether there were more.`,
    `- Density \`step\`: ${LIMITS.densitySteps.join(', ')} yards.`,
    '',
  );
  return lines.join('\n');
}
